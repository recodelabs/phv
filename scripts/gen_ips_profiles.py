#!/usr/bin/env python3
"""Generate data/ips-profiles.json from unpacked hl7.fhir.uv.ips and hl7.fhir.r4.core packages.

Usage:
  mkdir -p /tmp/ips /tmp/r4core
  curl -sL https://packages.fhir.org/hl7.fhir.uv.ips/2.0.0 | tar -xz -C /tmp/ips
  curl -sL https://packages.fhir.org/hl7.fhir.r4.core/4.0.1 | tar -xz -C /tmp/r4core
  python3 scripts/gen_ips_profiles.py /tmp/ips/package /tmp/r4core/package data/ips-profiles.json

Keeps the snapshot of every IPS resource and data type profile, plus the core vitalsigns
profile that the IPS vital signs section points to. Narrative and descriptive fields are
removed. Both packages are published by HL7 under CC0.
"""
import json
import os
import sys

IPS_VERSION = "2.0.0"
CORE_PROFILES = ["vitalsigns"]

# Element fields that only describe, and play no part in validation.
DROP_ELEMENT = {
    "short", "definition", "comment", "requirements", "alias", "mapping", "example",
    "meaningWhenMissing", "isModifierReason", "orderMeaning",
}
KEEP_DEFINITION = {
    "resourceType", "url", "version", "name", "status", "fhirVersion", "kind", "abstract",
    "type", "baseDefinition", "derivation",
}


def strip_element(element):
    element = {k: v for k, v in element.items() if k not in DROP_ELEMENT}
    if "binding" in element:
        element["binding"] = {k: v for k, v in element["binding"].items() if k != "extension"}
    for constraint in element.get("constraint", []):
        constraint.pop("extension", None)
        constraint.pop("source", None)
        constraint.pop("xpath", None)
        constraint.pop("requirements", None)
    element.pop("extension", None)
    return element


def strip(definition):
    out = {k: v for k, v in definition.items() if k in KEEP_DEFINITION}
    out["snapshot"] = {"element": [strip_element(e) for e in definition["snapshot"]["element"]]}
    return out


def load(path):
    with open(path) as handle:
        return json.load(handle)


def main(ips_dir, core_dir, output_path):
    package = load(os.path.join(ips_dir, "package.json"))
    if package["version"] != IPS_VERSION:
        sys.exit(f"expected hl7.fhir.uv.ips {IPS_VERSION}, got {package['version']}")
    profiles = []
    for name in sorted(os.listdir(ips_dir)):
        if not (name.startswith("StructureDefinition-") and name.endswith(".json")):
            continue
        definition = load(os.path.join(ips_dir, name))
        if definition.get("kind") == "logical" or definition.get("type") == "Extension":
            continue
        if definition.get("derivation") != "constraint":
            continue
        # octofhir cannot check the Bundle profile: every entry matches every slice.
        # phv checks the Bundle itself.
        if definition.get("type") == "Bundle":
            continue
        profiles.append(strip(definition))
    for name in CORE_PROFILES:
        profiles.append(strip(load(os.path.join(core_dir, f"StructureDefinition-{name}.json"))))
    data = {
        "source": f"hl7.fhir.uv.ips#{IPS_VERSION} and hl7.fhir.r4.core#4.0.1 (CC0), "
        "generated by scripts/gen_ips_profiles.py",
        "profiles": profiles,
    }
    with open(output_path, "w") as handle:
        json.dump(data, handle, separators=(",", ":"), sort_keys=True)
        handle.write("\n")
    print(f"wrote {len(profiles)} profiles to {output_path}", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
